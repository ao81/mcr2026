// クランク・レーンチェンジごとの寸法（COURSE_LIST_USE が 1 のとき使う。issue #2）
//   1つのコースにクランクやレーンチェンジが何回か出てきて、ラインから曲がり角までの距離や、
//   ラインの幅がそれぞれ違う。COURSE_LIST に、コース1周分を走る順に1行ずつ書く（クランクもレーンチェンジも同じ表に書く）。
//   ・種類   … 'C' クランク（クロスライン）、'H' レーンチェンジ（ハーフライン）
//   ・距離   … クロスライン（ハーフライン）の終わりから、曲がり角（中央線が切れる所）まで [m]。コース図の寸法
//   ・線の幅 … クロスライン（ハーフライン）の進行方向の幅 [m]。コース図の「幅○○mm」をそのまま書く
//              センサには実際より少し広く見えるので、その分は下の LINE_SEEN_EXTRA_M で全部の線にまとめて足す
//   ・向き   … 'R' 右、'L' 左
//   スタートの位置が何通りかあるとき（外側の直線からも内側の直線からもスタートするなど）：
//   ・COURSE_START_ROWS に、スタートしてから最初に来るのが表の何行目か（0から数える）を、あり得るものを全部書く
//   ・どれか分からない間は、あり得る行の中で一番短い距離・一番広い線の幅を使う（ブレーキが早くなる側）。
//     クランクで曲がった向き、ハーフラインの向きと合わない行は外していき、1つに決まったら、その後は表の値どおりに走る
//     （このコースなら、1つ目のクランクで曲がった向きで決まる。右なら外側、左なら内側からのスタート）
//   ・スタートの位置が1つに決まっているときは、その行だけを書く（1つ目から表の値どおりに走る）
//   数え間違いへの備え：
//   ・どの行とも合わなくなったら（線の見間違いなど）、それより後は、表の中でその種類の一番短い距離と
//     一番広い線の幅を使う（遅くはなるが曲がれる側）
//   ・クランクの向きは曲がり角に着くまで分からないので、合わないと分かるのは、そのクランクの減速が終わった後になる。
//     表の順番を間違えると、そのクランクでは間違えた距離のまま減速するので、順番はよく確かめる
#define LINE_SEEN_EXTRA_M       0.010f   // 表の線の幅に足す分 [m]（センサが白と判定する範囲の分だけ、線は実際より広く見える）
                                         //   2026-11-25 0.000 → 0.010：CRK0056 の通過時間から 0.005〜0.010 と見積もった。0 のままだと曲がり角の線で測る速さが 3 割ほど遅く出て、曲がり始めが遅れる（FULL0053・CRK0056）
                                         //   線の幅によらず、ほぼ同じ量になる（センサの性質で決まる）。docs/tuning_guide.md 3-3 の方法で測った
                                         //   「センサで見た幅 − コース図の幅」を入れる（模擬ではセンサの見える範囲 ±4mm で 0.008）
                                         //   ※ 小さすぎると速さを少なく見積もり、ブレーキが遅れる。迷ったら大きめにする（早めに減速する側）
struct CourseSpot {
    char kind;        // 'C' クランク / 'H' レーンチェンジ
    float to_m;       // 距離 [m]
    float line_w_m;   // 線の幅 [m]
    char dir;         // 'R' 右 / 'L' 左
};
