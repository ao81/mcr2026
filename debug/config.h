//========================================
// タイヤのグリップ（すべらずに出せる加速度の上限）[m/s²]
//   横と前後を同時に使うときは「摩擦円」で考える：(前後/GRIP_LONG)² + (横/GRIP_LAT)² ≦ 1
//========================================
#define GRIP_LAT_MPS2           7.0f    // 曲がるときの横向き（★実測する）
#define GRIP_LONG_MPS2          6.0f    // 加速・ブレーキの前後向き（★実測する）
// 計算に使うのは、測った値にこの割合をかけた値。1.0 で理論上の限界（測った値どおりなら最速）
//   タイヤの汚れや温度でグリップは変わり、ラインの通過時間で測る速さにも ±4% ほどの誤差があるので、少し下げておく。
//   下げるほど遅く、安全になる。模擬では 0.9 のとき、本当のグリップが 10% 低くても失敗しなかった。
//   余裕をすべてなくす（この2つを 1.0、COURSE_MARGIN_M と *_BRAKE_MARGIN_M を 0）と、
//   車の値が config.h と同じでも、速さの測定の誤差だけでクランクを 7回中5回失敗した
#define PLAN_GRIP_RATIO_LAT     0.90f   // 横向き：曲がる速さ v = √(グリップ × 半径) は、0.9 にすると約 5% 遅くなる
#define PLAN_GRIP_RATIO_LONG    0.90f   // 前後向き：ブレーキを始める位置が早くなる

//========================================
// 速度の推定（モータの出力から車の速さを計算する）
//   v は「出力/100 × V_MAX_MPS」に向かって、時定数 MOTOR_TAU_S で近づくと考える
//     dv/dt = (出力/100 × V_MAX_MPS − v) ÷ MOTOR_TAU_S
//     （ただし加速は GRIP_LONG_MPS2、減速は GRIP_LONG_MPS2 × PLAN_GRIP_RATIO_LONG を超えない。どちらも推定が速めになる側）
//   ライン（幅が分かっている）を通過したときは、その通過時間で v を測り直す
//========================================
#define V_MAX_MPS               1.8f    // 出力100%で走り続けたときの速さ [m/s]（★実測する。LOG0008 のライン通過時間から約 1.7〜1.8。USE_NEW_VMAX_LEARN が 1 なら最初のラインで直る）
#define MOTOR_TAU_S             0.15f   // 速さが変化するときの時定数 [s]（★実測する）
#define LINE_PASS_OFFSET_MS     1       // 測った通過時間に足す分 [ms]。センサは1msごとに見るので、
                                        //   始まり：ラインに乗ってから見つけるまで平均 0.5ms ＋ 見つけた次の割り込みから数え始めるので 1ms → 1.5ms 足りない
                                        //   終わり：ラインを出てから気づくまで平均 0.5ms 多く数える → 差し引き 1ms 足す
// USE_NEW_VMAX_LEARN：ラインを通過するたびに「測った速さ ÷ 推定していた速さ」で V_MAX を直す
//   新しい V_MAX = V_MAX × (1 + K × (比 − 1))、推定していた速さも同じ割合で直す
//   K（どれだけ測定を信じるか）は、今の V_MAX の誤差の大きさ P と、測定の誤差の大きさ R から K = P ÷ (P + R) で決める
//   （カルマンフィルタ。2つの誤差の2乗の和が最も小さくなる混ぜ方）。直した後の誤差は P × (1 − K) になるので、
//   測るたびに K は小さくなる（何回かの測定の平均に近づく）
//     P の初め   = VMAX_LEARN_SD²
//     R          = (0.41ms ÷ 通過時間)² ＋ LINE_WIDTH_SD²（0.41ms は 1ms 単位で測る始まりと終わりのずれ）
//   例：初めの1回（通過時間 13ms）は K ≈ 0.85。V_MAX_MPS の誤差が 20% あっても、1回で 3% ほどまで縮まる
#define VMAX_LEARN_SD           0.10f   // V_MAX_MPS の誤差の大きさ（電池の電圧などで 10% くらいずれる）
#define LINE_WIDTH_SD           0.03f   // センサで見たラインの幅の誤差の大きさ（CROSS/HALF_LINE_WIDTH_M の 3%）
#define VMAX_LEARN_MIN_GAIN     0.30f   // K をこれより小さくしない（走っている間に電池の電圧が下がっていくのにも合わせる）
#define VMAX_LEARN_RANGE        0.25f   // V_MAX_MPS の ±25% の範囲でだけ直す（測り間違いで大きく外れないように）
// 同じ出力を長く出し続けた後のラインでは、上の少しずつ直す方法ではなく、測った速さから v_max を1回で求める
//   （V_MAX_MPS が 3.0 で本当は 1.8 のように大きくずれていても、最初のクロスライン・ハーフラインで直る。
//    求めた値を、それ以後の ±VMAX_LEARN_RANGE の中心にする）
#define VMAX_STEADY_MS          600     // この時間 [ms] 以上同じ出力のときだけ使う（MOTOR_TAU_S の4倍ほど。★時定数を測ったら合わせる）
#define VMAX_STEADY_TOL         3.0f    // 出力の変化がこれ [%] 以内なら同じ出力とみる（直線でハンドルの左右に合わせて内輪が少し変わる分）
#define VMAX_STEADY_MIN_RATIO   0.40f   // 求めた値が V_MAX_MPS のこの倍から
#define VMAX_STEADY_MAX_RATIO   2.00f   //   この倍の間のときだけ使う（それ以外は測り間違いとみる）

