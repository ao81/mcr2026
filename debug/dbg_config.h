//**************************************************************************
// dbg_config.h  デバッグモードの設定（debug/ だけで使う。sync.sh で上書きされない）
//
//   通常のログ（logNNNN.csv、10ms ごと）とは別に、決めた区間だけを数 ms ごと（変化した瞬間は 1ms 単位）に RAM へ記録し、
//   走り終わってプッシュスイッチでログを閉じた後に dbgNNNN.csv（NNNN は通常ログと同じ番号）へ書き出す。
//   走っている間は microSD に書かないので、走りの判断の時間には影響しない。
//
//   RAM には最後の DBG_SAMPLES 個だけが残る（古いものから上書き）。
//   選んだ区間が終わって DBG_POST_MS たったら記録を止める。区間の前の様子も、入る分だけ残る。
//   区間の前にコースアウトなどで止まった場合は、止まった所で記録を止める（止まる直前の様子が残る）。
//**************************************************************************
#ifndef DBG_CONFIG_H
#define DBG_CONFIG_H

#define DBG_ENABLE        1     // 0 にすると詳しいログを取らない（通常のログだけになる）

// 記録する区間
//   1 : クランク（クロスラインを見つけてから、曲がり終えて通常走行に戻るまで。pattern 100〜161）
//   2 : レーンチェンジ（ハーフラインを見つけてから、通常走行に戻るまで。pattern 200〜202, 300〜450, 500〜502, 600〜750）
//   3 : 時間で指定（スタートから DBG_FROM_MS 〜 DBG_TO_MS）
#define DBG_AUTO_STOP     1     // 1: 区間終了で車体を停止し、専用CSVを自動保存
// 4 : カーブ（操舵の継続で検出）
// 5 : 直前の特殊区間の出口から指定標識まで（最初はスタートから）
// 6 : スタートから指定標識までの総合タイム
#define DBG_TRIAL_ID      0UL        // タイム比較画面が設定ごとに発行する番号
#define DBG_TARGET        6
#define DBG_TARGET_NO     1     // 何回目の区間を記録するか（1 = スタートして最初のクランク）。0 なら止まるまで記録し続け、最後の DBG_SAMPLES 個を残す
#define DBG_FROM_MS       0     // DBG_TARGET 3 のとき：記録を始める時間 [ms]
#define DBG_TO_MS         1000  // DBG_TARGET 3 のとき：記録を止める時間 [ms]

#define DBG_INTERVAL_MS   10    // 記録する間隔 [ms]（1 にすると細かくなるが、残る時間は半分になる）
#define DBG_SAMPLES       350   // RAM に残す行の数。1行 26 バイト（600 行で 15.6KB。前は 24 バイト × 450 = 10.8KB）。
                                //   変化した瞬間の行がなければ、残る時間 = DBG_INTERVAL_MS × DBG_SAMPLES（5ms × 600 = 3.0 秒）。
                                //   変化した瞬間の行を上限（DBG_CHANGE_MAX）まで足しても、区間に入ってから (600 − 20 − 150) × 5ms = 2.15 秒は残る（前と同じ）。
                                //   実車のクランクは、クロスラインから通常走行に戻るまで 0.45〜1.7 秒（CRK0042〜0110）
                                //   書き込みの時に RAM が足りないと言われたら減らす
#define DBG_POST_MS       800       // 区間が終わってから、さらに記録を続ける時間 [ms]（通常走行に戻った後の揺れを見るため）
// 変化した瞬間の行（詳細ログ）
//   決まった間隔（DBG_INTERVAL_MS）の間でも、pattern・センサ・ブレーキなどの状態・ラインの通過時間が変わった ms と、
//   モータ出力やハンドルの指令が大きく変わった ms の行を足す。線を見つけた・ブレーキを始めた・曲がり始めた時刻が 1ms 単位で分かる。
//   選んだ区間に入ってから記録を止めるまでの間だけ足す（通常走行・総合（DBG_TARGET 5・6）では足さない）
#define DBG_CHANGE_ROWS   1     // 1: 変化した瞬間の行を足す　0: 決まった間隔の行だけ（前と同じ）
#define DBG_CHANGE_MAX    150   // 1回の区間で足す数の上限（センサがちらついても、区間の始まりが押し出されないように）
#define DBG_CHG_MOTOR     10    // モータ出力がこの値 [%] 以上変わったら（前進とブレーキが入れ替わったときも）行を足す
#define DBG_CHG_STEER10   20    // ハンドルの指令がこの値 [0.1度] 以上変わったら行を足す（20 = 2度）

#define DBG_PRE_KEEP      20    // 区間が DBG_SAMPLES 個分より長く続いたとき、区間に入る前の様子を残す数。
                                //   区間の始まりが上書きされる前に記録を止める（DBG_AUTO_STOP が 1 なら車も止まる）

#endif
