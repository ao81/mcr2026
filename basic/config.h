const int LANE_RAMP[LANE_STEPS] = {
     -5,   0,   5,  10,  15,  20,  25,  30,  35,  40,  45,
     50,  55,  60,  65,  70,  75,  79,  83,  87,  91,  95 };

//************************************************************************
// ここから下は「新しい走行アルゴリズム」の設定（speed_model.ino）
//   スイッチを 0 にすると元のプログラムと同じ動き、1 にすると新しい動きになる。
//   実機で1つずつ 1 にして確かめること（手順は docs/tuning_guide.md）
//************************************************************************
#define USE_NEW_CRANK_BRAKE     0   // クランク手前の減速を、速度と残り距離から計算する
#define USE_NEW_LANE_BRAKE      0   // レーンチェンジ手前の減速を、速度と残り距離から計算する
#define USE_NEW_TRACE_SPEED     0   // 通常走行のモータ値を、ハンドル角度（曲がりの半径）から計算する

//========================================
// 車体の寸法 [m]
//========================================
#define WHEELBASE_M             0.170f  // 前輪の軸と後輪の軸の距離
#define TREAD_M                 0.150f  // 左右の後輪の中心どうしの距離

//========================================
// 速度の推定（モータの出力から車の速さを計算する）
//   v は「指令した出力 × V_MAX_MPS」に向かって、時定数 MOTOR_TAU_S で近づくと考える
//     dv/dt = (出力/100 × V_MAX_MPS − v) ÷ MOTOR_TAU_S
//   ライン（幅が分かっている）を通過したときは、その通過時間で v を測り直す
//========================================
#define V_MAX_MPS               3.0f    // 出力100%で走り続けたときの速さ [m/s]（★実測する）
#define MOTOR_TAU_S             0.15f   // 速さが変化するときの時定数 [s]（★実測する）
#define CROSS_LINE_WIDTH_M      0.020f  // クロスラインの進行方向の幅 [m]（0 にすると測り直さない）
#define HALF_LINE_WIDTH_M       0.020f  // ハーフラインの進行方向の幅 [m]（0 にすると測り直さない）
#define LINE_PASS_OFFSET_MS     2       // 通過時間の測り始めが遅れる分 [ms]（ライン検出から計測開始まで2回の割り込みがある）

//========================================
// クランク手前の減速（USE_NEW_CRANK_BRAKE）
//   「全開 → ぎりぎりで最大ブレーキ → 目標の速さで進入」を、残り距離から毎ms判断する
//========================================
#define CROSS_TO_CRANK_M        0.50f   // クロスラインの終わりからクランクまでの距離 [m]（★コースに合わせる）
#define CRANK_ENTRY_MPS         1.4f    // クランクに入るときの速さ [m/s]（★実測して上げていく）
#define CRANK_BRAKE_POWER       (-60)   // ブレーキのときのモータ出力（マイナスは逆転）
#define CRANK_BRAKE_MARGIN_M    0.10f   // 計算の誤差に備えて、早めにブレーキをかける距離 [m]

//========================================
// レーンチェンジ手前の減速（USE_NEW_LANE_BRAKE）
//========================================
#define HALF_TO_LANE_M          0.50f   // ハーフラインの終わりから中央線が切れる所までの距離 [m]（★コースに合わせる）
#define LANE_ENTRY_MPS          1.8f    // 車線変更を始めるときの速さ [m/s]（★実測して上げていく）
#define LANE_BRAKE_POWER        (-60)
#define LANE_BRAKE_MARGIN_M     0.10f

//========================================
// 通常走行の速度（USE_NEW_TRACE_SPEED）
//   ハンドル角度 θ のときの曲がりの半径 R = WHEELBASE_M ÷ tan(θ)
//   曲がれる速さの上限 v = √(LATERAL_ACCEL × R)  → 外輪の出力 = v ÷ V_MAX_MPS × 100
//   内輪の出力 = 外輪 × (R − TREAD_M/2) ÷ (R + TREAD_M/2)   （内輪と外輪の回る距離の比）
//========================================
#define LATERAL_ACCEL           8.0f    // 横すべりせずに曲がれる横向きの加速度 [m/s²]（★実測する）
#define TRACE_MIN_POWER         30      // 外輪の出力の下限

//========================================
// ログ（microSD）
//========================================
#define LOG_INTERVAL_MS         10      // ログを取る間隔
#define LOG_MAX                 100     // RAMに貯めるログの数。ログが飛ぶときは増やす
#define LOG_SPEED_MODEL         0       // 1 にすると、推定した速さ[mm/s]と距離[mm]の列をログに追加する（調整用）

#endif
