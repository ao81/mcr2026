//**************************************************************************
// config.h  調整用パラメータ（走行を調整するときは、まずこのファイルを見る）
//
//  ・時間の単位はすべて ms（1msの割り込み1回 = 1ms）
//  ・モータ値は -100〜100（%）。実際の出力は DIPスイッチで 70〜100% に縮小される
//  ・ハンドル角度はプラスが右、マイナスが左（単位は度）
//  ・センサ別の細かい数値の表は tables.h にある
//**************************************************************************
#ifndef MCR_CONFIG_H
#define MCR_CONFIG_H

//========================================
// ハードウェア
//========================================
// PWM周期 (HOCO 48MHz を 16分周 = 3MHz でカウント)
#define PWM_CYCLE       32999   // サーボ  11ms = 33000カウント
#define PWM_CYCLE_M     14999   // モータ   5ms = 15000カウント
#define SERVO_CENTER    5150    // ハンドルが真っすぐになるPWM値（車体ごとに合わせる）
#define HANDLE_STEP     23      // 1度あたりのPWM値
#define SERVO_DIR       (-1)    // サーボが左右逆に動くときは (+1) にする

// DIPスイッチによる速度の縮小: 出力 = 指定値 × (DIP値 + DIP_SPEED_BASE) ÷ 10
//   DIP=0 → 70%, 1 → 80%, 2 → 90%, 3 → 100%
#define DIP_SPEED_BASE  7

//========================================
// 安全装置・停止
//========================================
#define AUTO_STOP_MS            5000    // スタートからこの時間で自動停止（★大会ではコース1周分より長くする）
#define COURSE_OUT_SENSOR       0xff    // この値が続いたらコースアウトと判断（全センサ白）
#define COURSE_OUT_MS           300     // 上の状態がこの時間続いたら停止
#define PUSH_STOP_GUARD_MS      1000    // スタート後この時間はプッシュスイッチによる停止を受け付けない
#define STOP_STEER_MS           200     // 自動停止後、ハンドルで線を追い続ける時間

//========================================
// 通常走行（pattern 20〜25）
//========================================
// 直線（センサ 0x18 / 0x1c / 0x38）がこの時間続くと、次の速度段階へ上がる
//   段階0→1: 350ms, 1→2: 650ms, 2→3: 900ms, 3→4: 1100ms, 4→5: 1250ms
#define TRACE_STAGES            6
const unsigned long TRACE_STAGE_UP_MS[TRACE_STAGES - 1] = { 350, 650, 900, 1100, 1250 };

// 大曲がり（pattern 30〜35, 40〜45）
// 段階 s の大曲がりは、この時間がたつと段階 s-1 の表に切り替わる
//   ※ 経過時間はリセットしないので、段階5なら125ms後に 4→3→2→1→0 と一気に下がる（元の動作のまま）
const unsigned long CURVE_STAGE_DOWN_MS[TRACE_STAGES] = { 0, 25, 50, 75, 100, 125 };

//========================================
// クロスライン・クランク（pattern 100〜161）
//========================================
#define CROSS_STRAIGHT_MS       100     // クロスライン通過後、クランク判定を始めるまでの時間
#define CRANK_ANGLE             50      // クランクでのハンドル最大角度
#define CRANK_ENTER_MS          70      // クランク突入（110/150）から低速旋回（111/151）へ移る時間

// クロスライン通過後の速度変化（newcrank）
//   k = クロスラインの通過時間[ms]（小さいほど速い）
//   段階 i = k - CRANK_K_MIN （0〜CRANK_STEPS-1 に制限）
//   ① 0 〜 CRANK_FULL_MS[i]            : 全開 100%
//   ② 〜 CRANK_HOLD_END_MS[i]          : CRANK_RAMP[i]（ブレーキ）
//   ③ その後 CRANK_RAMP_STEP_MS ごとに  : CRANK_RAMP[i+1], [i+2] ... と上げていく（最後の値で止まる）
#define CRANK_K_MIN             11
#define CRANK_STEPS             25
#define CRANK_RAMP_STEP_MS      16
const int CRANK_FULL_MS[CRANK_STEPS] = {
     18,  24,  30,  36,  42,  48,  54,  60,  66,  72,
     78,  84,  90,  96, 102, 108, 114, 120, 126, 132,
    138, 144, 150, 156, 162 };
const int CRANK_HOLD_END_MS[CRANK_STEPS] = {
     59,  75,  91, 107, 123, 139, 155, 171, 187, 203,
    219, 235, 251, 267, 283, 299, 315, 331, 347, 363,
    379, 395, 411, 427, 443 };
const int CRANK_RAMP[CRANK_STEPS] = {
    -35, -30, -25, -20, -15, -10,  -5,   0,   5,  10,
     15,  20,  25,  30,  35,  41,  47,  53,  59,  65,
     71,  77,  83,  89,  95 };

//========================================
// レーンチェンジ（pattern 200〜450, 500〜750）
//========================================
// ハーフラインの通過時間 k[ms] で段階 0〜10 を決める
//   k <= LANE_STAGE_LIMIT[0] なら段階0, <= [1] なら段階1 ... どれにも当てはまらなければ段階10
#define LANE_STAGES             11
const int LANE_STAGE_LIMIT[LANE_STAGES - 1] = { 12, 15, 18, 21, 24, 27, 30, 33, 36, 39 };

#define LANE_START_WAIT_MS      50      // ハーフライン通過後、白線の切れ目を探し始めるまでの時間
#define LANE_STEER_ANGLE        16      // 車線変更で切るハンドル角度（左はマイナスにして使う）
#define LANE_STRAIGHT_ANGLE     2       // 切り終わった後に戻す角度（右は -2、左は +2 として使う）

// 段階ごとの値（段階0〜10）。外輪=曲がる方向と反対側のモータ
const int LANE_STEER_OUTER[LANE_STAGES]      = {  75,  76,  77,  78,  79,  80,  81,  82,  83,  84,  85 };
const int LANE_STEER_INNER[LANE_STAGES]      = {  30,  32,  34,  36,  38,  40,  42,  44,  46,  48,  50 };
const unsigned long LANE_STEER_MS[LANE_STAGES] = { 155, 156, 157, 158, 159, 160, 161, 162, 163, 164, 165 };
const int LANE_STRAIGHT_SPEED[LANE_STAGES]   = {  80,  81,  82,  83,  84,  85,  86,  87,  88,  89,  90 };

// ハーフライン通過後の速度変化（shasenhenkou）。考え方はクランクと同じ
#define LANE_K_MIN              5
#define LANE_STEPS              22
#define LANE_RAMP_STEP_MS       6
const int LANE_FULL_MS[LANE_STEPS] = {
     75,  80,  86,  93, 101, 110, 120, 131, 143, 156, 170,
    185, 201, 218, 236, 255, 275, 296, 318, 341, 365, 390 };
const int LANE_HOLD_END_MS[LANE_STEPS] = {
     81,  86,  92,  99, 107, 116, 126, 137, 149, 162, 176,
    191, 207, 224, 242, 261, 281, 302, 324, 347, 371, 396 };
const int LANE_RAMP[LANE_STEPS] = {
     -5,   0,   5,  10,  15,  20,  25,  30,  35,  40,  45,
     50,  55,  60,  65,  70,  75,  79,  83,  87,  91,  95 };

//========================================
// ログ（microSD）
//========================================
#define LOG_INTERVAL_MS         10      // ログを取る間隔
#define LOG_MAX                 100     // RAMに貯めるログの数。ログが飛ぶときは増やす

#endif
