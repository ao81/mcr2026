//************************************************************************
// ここから下は「新しい走行アルゴリズム」の設定（speed_model.ino, planner.ino）
//   スイッチを 0 にすると元のプログラムと同じ動き、1 にすると新しい動きになる。
//   どれも実機では試していない。1つずつ 1 にして確かめること（手順は docs/tuning_guide.md）
//   ★の付いた数値は、車体やコースに合わせて測った値を入れる
//************************************************************************
#define USE_NEW_TRACTION        0   // 加速の出力を、タイヤが空回りしない範囲に制限する
#define USE_NEW_TRACE_SPEED     0   // 通常走行(20〜25)の速さを、ハンドル角度から決まる「曲がれる上限の速さ」にする
#define USE_NEW_CURVE_SPEED     0   // 大曲がり(30〜45)の速さも、同じ方法で決める
#define USE_NEW_STEER           0   // 通常走行(20〜25)のハンドル角度を、線の位置から計算する（ピュアパシュート）
#define USE_NEW_CRANK_BRAKE     0   // クランク手前の減速を、速さと残りの距離から計算する（USE_NEW_CRANK_TURN が 0 なら CRANK_ENTRY_MPS も入れる）
#define USE_NEW_CRANK_TURN      0   // クランクを、コースからはみ出さない最大の半径の円弧で曲がる
#define USE_NEW_LANE_BRAKE      0   // レーンチェンジ手前の減速を、速さと残りの距離から計算する（USE_NEW_LANE_STEER と一緒に使う）
#define USE_NEW_LANE_STEER      0   // レーンチェンジを、同じ半径の円弧2つをつないだ最も緩い経路で行う
#define USE_NEW_VMAX_LEARN      0   // ラインの通過で測った速さから、出力100%のときの速さ（電池の電圧で変わる）を走りながら直す（ラインの幅を合わせてから使う）

//========================================
// 車体の寸法 [m]
//========================================
#define WHEELBASE_M             0.170f  // 前輪の軸と後輪の軸の距離（★）
#define TREAD_M                 0.150f  // 左右の後輪の中心どうしの距離（★）
#define SENSOR_TO_REAR_AXLE_M   0.250f  // 後輪の軸からセンサまでの距離（★）
// センサ8個の左右の位置 [mm]。左端(bit7)から右端(bit0)の順。車体の中心が0、右がプラス（★）
const int SENSOR_X_MM[8] = { -35, -25, -15, -5, 5, 15, 25, 35 };
// コースの外に出てはいけない部分の大きさ（クランクとレーンチェンジの経路の計算に使う）
//   タイヤだけがコース上にあればよい場合：前輪までの距離と、タイヤの外側までの幅の半分を入れる
//   車体全体がコース上にないといけない場合：車体の前の端までの距離と、車体の幅の半分を入れる（★大会の規則で確認）
#define CAR_FRONT_M             0.170f  // 後輪の軸から、その部分の一番前まで
#define CAR_HALF_WIDTH_M        0.090f  // その部分の幅の半分
#define SERVO_MAX_ANGLE         50      // 計算で使ってよいハンドル角度の上限 [度]
#define SERVO_SPEED_DPS         600.0f  // サーボが角度を変える速さ [度/s]（★サーボの仕様。例: 0.10秒/60度 → 600）
#define SERVO_DEAD_S            0.010f  // 指令を出してからサーボが動き始めるまでの遅れ [s]（サーボのPWM周期 11ms の半分ほど）

//========================================
// コースの寸法 [m]（規則の範囲で、いちばん厳しい値を初期値にしている）
//========================================
#define COURSE_WIDTH_M          0.300f  // コースの幅
#define COURSE_MARGIN_M         0.020f  // コースの端から、さらに残しておく余裕（クランク・レーンチェンジの経路の計算に使う）
                                        //   0 で理論上の限界。サーボの速さ・センサの位置・速さの推定の誤差の分を残す
                                        //   （模擬では 0.010 だと、サーボが 2/3 の速さのときやセンサが 2cm ずれたときにクランクでコースアウトした）
#define TRACE_MIN_RADIUS_M      0.450f  // カーブの最小半径（規則 450mm 以上。USE_NEW_STEER で使う）
#define CROSS_LINE_WIDTH_M      0.040f  // クロスラインの進行方向の幅（規則 20〜40mm。★大会のコースで測る）
#define HALF_LINE_WIDTH_M       0.040f  // ハーフラインの進行方向の幅（同上）
                                        //   ※ センサが白と判定する範囲の分だけ、線は実際より広く見える。走らせて合わせる（docs/tuning_guide.md 3-3）
                                        //   ※ 実際より広い値にすると速さを多めに見積もる（早めに減速する）ので安全側
#define CROSS_TO_CRANK_M        0.50f   // クロスラインの終わりからクランクの曲がり角まで（規則 500〜1000mm）
#define HALF_TO_LANE_M          0.30f   // ハーフラインの終わりから中央線が切れる所まで（規則 300〜1000mm）
#define LANE_SHIFT_M            0.300f  // 車線変更で横に動く距離（元の線と新しい線の間隔）
#define LANE_SECTION_M          0.600f  // 中央線が切れてから、新しい車線だけになるまでの長さ（★）

//========================================
// タイヤのグリップ（すべらずに出せる加速度の上限）[m/s²]
//   横と前後を同時に使うときは「摩擦円」で考える：(前後/GRIP_LONG)² + (横/GRIP_LAT)² ≦ 1
//========================================
#define GRIP_LAT_MPS2           8.0f    // 曲がるときの横向き（★実測する）
#define GRIP_LONG_MPS2          6.0f    // 加速・ブレーキの前後向き（★実測する）
// 計算に使うのは、測った値にこの割合をかけた値。1.0 で理論上の限界（測った値どおりなら最速）
//   タイヤの汚れや温度でグリップは変わり、ラインの通過時間で測る速さにも ±4% ほどの誤差があるので、少し下げておく。
//   下げるほど遅く、安全になる。模擬では 0.9 のとき、本当のグリップが 10% 低くても失敗しなかった。
//   余裕をすべてなくす（この2つを 1.0、COURSE_MARGIN_M と *_BRAKE_MARGIN_M を 0）と、
//   車の値が config.h と同じでも、速さの測定の誤差だけでクランクを 7回中5回失敗した
#define PLAN_GRIP_RATIO_LAT     0.90f   // 横向き：曲がる速さ v = √(グリップ × 半径) は、0.9 にすると約 5% 遅くなる
#define PLAN_GRIP_RATIO_LONG    0.90f   // 前後向き：ブレーキを始める位置が早くなる

//========================================
// 速度の推定（モータの出力から車の速さを計算する）
//   v は「出力/100 × V_MAX_MPS」に向かって、時定数 MOTOR_TAU_S で近づくと考える
//     dv/dt = (出力/100 × V_MAX_MPS − v) ÷ MOTOR_TAU_S
//     （ただし加速は GRIP_LONG_MPS2、減速は GRIP_LONG_MPS2 × PLAN_GRIP_RATIO_LONG を超えない。どちらも推定が速めになる側）
//   ライン（幅が分かっている）を通過したときは、その通過時間で v を測り直す
//========================================
#define V_MAX_MPS               3.0f    // 出力100%で走り続けたときの速さ [m/s]（★実測する）
#define MOTOR_TAU_S             0.15f   // 速さが変化するときの時定数 [s]（★実測する）
#define LINE_PASS_OFFSET_MS     2       // 通過時間の測り始めが遅れる分 [ms]（ライン検出から計測開始まで2回の割り込みがある）
// USE_NEW_VMAX_LEARN：ラインを通過するたびに「測った速さ ÷ 推定していた速さ」で V_MAX を直す
//   新しい V_MAX = V_MAX × (1 + VMAX_LEARN_GAIN × (比 − 1))
//   通過時間は 1ms 単位なので1回の測定には ±7% ほどの誤差がある。1.0 にすると誤差をそのまま受けるため、半分ずつ直す
#define VMAX_LEARN_GAIN         0.5f
#define VMAX_LEARN_RANGE        0.25f   // V_MAX_MPS の ±25% の範囲でだけ直す（測り間違いで大きく外れないように）

//========================================
// クランク（USE_NEW_CRANK_BRAKE / USE_NEW_CRANK_TURN）
//========================================
#define CRANK_ENTRY_MPS         0.0f    // クランクに入る速さ [m/s]。0 なら円弧の半径とグリップから自動で計算する（USE_NEW_CRANK_TURN が 1 のとき）
                                        //   USE_NEW_CRANK_TURN が 0 のときは、元の曲がり方でうまく曲がれる速さを入れる（模擬では 1.4 前後）
#define CRANK_BRAKE_POWER       (-60)   // ブレーキのときのモータ出力（マイナスは逆転）
#define CRANK_BRAKE_MARGIN_M    0.05f   // 計算の誤差に備えて、早めにブレーキをかける距離 [m]（距離の推定の誤差 ±5% × 1m 分）
#define CRANK_ARC_EXIT_RATIO    0.70f   // 円弧をこの割合まで進んだら、新しい線が見えた時点で通常走行へ移る

